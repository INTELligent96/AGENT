# ================ CONFIG PATCH ================
def patch_config():
    path = "config.yaml"
    if not os.path.exists(path):
        print("[SKIP] config.yaml не найден")
        return
    with open(path, "r", encoding="utf-8") as f:
        content = f.read()
    if "allowed_paths:" in content:
        print("[SKIP] config.yaml - allowed_paths уже есть")
        return
    # Ищем блок safety и добавляем строку после read_only_originals
    lines = content.split("\n")
    out = []
    inserted = False
    for line in lines:
        out.append(line)
        if not inserted and line.strip().startswith("read_only_originals:"):
            indent = line[: len(line) - len(line.lstrip())]
            out.append(indent + "allowed_paths: []   # Пусто = без ограничений. Иначе список разрешённых корней.")
            inserted = True
    if not inserted:
        # Если блок safety не найден — добавляем в конец
        out.append("")
        out.append("safety:")
        out.append("  allowed_paths: []")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("[OK] config.yaml - добавлен allowed_paths")


